"""The ``Store`` port: what core needs from a project's storage."""

from __future__ import annotations

from contextlib import AbstractAsyncContextManager
from typing import Any, Protocol

from plotroom.core.actions import Action
from plotroom.core.events import Event
from plotroom.core.github import FetchCursor, GitHubSummary, PullRequest
from plotroom.core.lanes import Lane
from plotroom.core.next_items import Item
from plotroom.ports.work_items import WorkItem

type Board = tuple[int, list[Item], dict[str, int], list[Lane]]


class Transaction(Protocol):
    """One open writer transaction (AD-14): all of it commits or rolls back together."""

    async def find_event(self, source: str, kind: str, upstream_id: str) -> Event | None:
        """The stored event with this identity, or ``None``."""
        ...

    async def insert_event(self, event: Event) -> None:
        """Store a new event whose ``seq`` came from ``allocate_seq`` in this transaction."""
        ...

    async def find_claude_turn(self, session: str, aliases: tuple[str, ...]) -> Event | None: ...

    async def bind_claude_turn(
        self, session: str, aliases: tuple[str, ...], event: str
    ) -> None: ...

    async def allocate_seq(self) -> int:
        """The project's next integer ``seq`` (AD-9). Rolled back with the transaction."""
        ...

    async def find_noop_receipt(self, command: str, key: str) -> dict[str, Any] | None: ...

    async def insert_noop_receipt(
        self, command: str, key: str, receipt: dict[str, Any]
    ) -> None: ...

    async def active_item_subjects(self, kind: str) -> set[str]: ...

    async def find_item(self, item_id: str) -> Item | None: ...
    async def active_item(self, key: str) -> Item | None: ...
    async def save_item(self, item: Item) -> None: ...

    async def insert_action(self, action: Action) -> None: ...

    async def update_action(self, action: Action) -> None: ...

    async def find_lane(self, lane_id: str) -> Lane | None: ...

    async def worker_lane(self, worker: str) -> Lane | None: ...

    async def branch_lane(self, branch: str) -> Lane | None: ...

    async def save_lane(self, lane: Lane) -> None: ...

    async def ready_work_items(self) -> tuple[WorkItem, ...]: ...

    async def replace_work_items(self, items: tuple[WorkItem, ...]) -> None: ...

    async def claimed_work_items(self) -> set[str]: ...

    async def pull_request(self, repository: str, number: int) -> PullRequest | None: ...

    async def save_pull_request(self, pull: PullRequest) -> None: ...

    async def fetch_cursor(self, repository: str, resource: str) -> FetchCursor | None: ...

    async def save_fetch_cursor(
        self, repository: str, resource: str, cursor: FetchCursor
    ) -> None: ...


class Store(Protocol):
    """One project's ledger storage (AD-4: a store is opened for exactly one project)."""

    @property
    def project_id(self) -> str: ...

    async def revision(self) -> str | None:
        """The schema revision the project file is at, or ``None`` for an unmigrated file."""
        ...

    def transaction(self) -> AbstractAsyncContextManager[Transaction]:
        """Open the project's one writer transaction.

        Commits when the block exits normally and rolls back on any exception. Only the project
        writer calls this (AD-3); a second concurrent entry raises ``RuntimeError``.
        """
        ...

    async def head_seq(self) -> int:
        """The last allocated ``seq`` (0 when nothing has been written). Reads committed state."""
        ...

    async def events_after(self, seq: int, limit: int = 100) -> list[Event]:
        """Committed events above ``seq``, ascending, at most ``limit``; none when it is below 1."""
        ...

    async def read_board(self, role: str) -> Board: ...

    async def read_github_board(
        self, role: str, repository: str
    ) -> tuple[Board, GitHubSummary]: ...

    async def pull_request(self, repository: str, number: int) -> PullRequest | None: ...

    async def fetch_cursor(self, repository: str, resource: str) -> FetchCursor | None: ...

    async def read_next(self, role: str, offset: int, limit: int) -> tuple[int, list[Item]]: ...

    async def read_open_item(self, role: str, item_id: str) -> Item | None: ...

    async def first_item_change(
        self, role: str, cursor: int
    ) -> tuple[int, dict[str, Any] | None]: ...

    async def pending_action(self) -> Action | None: ...

    async def ready_work_items(self) -> tuple[WorkItem, ...]: ...

    async def close(self) -> None: ...
